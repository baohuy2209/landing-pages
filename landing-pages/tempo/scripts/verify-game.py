"""Generate the fixed game's legal positions. Tooling only: pip install python-chess.
No chess engine or third-party chess code is shipped to the browser.
Run from any directory: python3 scripts/verify-game.py
"""
import json
from pathlib import Path
import chess
import chess.pgn
root = Path(__file__).resolve().parent.parent
with (root / 'public/games/kasparov-topalov-1999.pgn').open() as stream:
    game = chess.pgn.read_game(stream)
assert game and not game.errors
board = game.board()
moves = []
fens = [board.board_fen()]
for move in game.mainline_moves():
    assert move in board.legal_moves
    entry = dict(notation=board.san(move), **{'from': chess.square_name(move.from_square)}, to=chess.square_name(move.to_square))
    board.push(move)
    moves.append(entry)
    fens.append(board.board_fen())
assert len(moves) == 87 and game.headers['Result'] == '1-0'
assert not board.is_checkmate()  # Topalov resigned; this is not a checkmate.
score = '// Generated by scripts/verify-game.py from the credited, local PGN.\nexport const gameMoves = [\n'
for move in moves:
    score += '  {\n' + ''.join(f'    {key}: {json.dumps(value)},\n' for key, value in move.items()) + '  },\n'
(root / 'lib/game-score.ts').write_text(score + '] as const;\n')
(root / 'tests/game-positions.json').write_text(json.dumps(fens, indent=2) + '\n')
print(f'Validated {len(moves)} legal plies, including both long castles. Final FEN: {board.fen()}')
